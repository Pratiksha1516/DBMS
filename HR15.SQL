SELECT 
    NAME, MARKS,
    RANK() OVER (ORDER BY MARKS DESC) AS Rank_Position
FROM STUDENTS;

SELECT NAME, MARKS, (MARKS * 100.0 / 100) AS Percentage
FROM STUDENTS;

SELECT MARKS, COUNT(*) 
FROM STUDENTS 
GROUP BY MARKS 
HAVING COUNT(*) > 1;
