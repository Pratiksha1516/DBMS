SELECT * FROM TRIANGLES;

SELECT * 
FROM TRIANGLES
WHERE A = B OR B = C OR A = C;

SELECT *
FROM TRIANGLES
WHERE A = B AND B = C;

SELECT *
FROM TRIANGLES
WHERE A<>B AND B<>C AND A<>C;

SELECT * 
FROM TRIANGLES
WHERE A + B > C 
  AND A + C > B 
  AND B + C > A;

--
SELECT * 
FROM TRIANGLES
WHERE A*A + B*B = C*C 
   OR A*A + C*C = B*B 
   OR B*B + C*C = A*A;

SELECT A, B, C, (A + B + C) AS Perimeter
FROM TRIANGLES;

SELECT A, B, C, GREATEST(A, B, C) AS LargestSide
FROM TRIANGLES;

SELECT A, B, C, LEAST(A, B, C) AS SmallestSide
FROM TRIANGLES;

SELECT A, B, C, (A + B + C) AS Perimeter
FROM TRIANGLES
ORDER BY Perimeter DESC;

SELECT *
FROM TRIANGLES
WHERE (A + B + C) > 60;

SELECT *
FROM TRIANGLES
WHERE MOD(A,2)=0 AND MOD(B,2)=0 AND MOD(C,2)=0;

SELECT *
FROM TRIANGLES
WHERE MOD(A,2)=1 AND MOD(B,2)=1 AND MOD(C,2)=1;

SELECT A, B, C, (A + B + C) / 2.0 AS SemiPerimeter
FROM TRIANGLES;

SELECT *
FROM TRIANGLES
WHERE A + B = C OR A + C = B OR B + C = A;

SELECT A, B, C
FROM TRIANGLES
WHERE GREATEST(A,B,C) - LEAST(A,B,C) > 10;

SELECT A, B, C, GREATEST(A,B,C) AS Longest
FROM TRIANGLES
ORDER BY Longest DESC;

SELECT COUNT(*) AS ValidTriangles
FROM TRIANGLES
WHERE A + B > C AND A + C > B AND B + C > A;
