CREATE TABLE TRIANGLES(
	A INT,
	B INT,
	C INT
);

INSERT INTO TRIANGLES(A, B, C) 
VALUES
(20, 20, 23),
(20, 20, 20),
(20, 21, 22),
(13, 14, 30);

SELECT * FROM TRIANGLES;

SELECT * 
FROM TRIANGLES
WHERE A = B OR B = C OR A = C;

SELECT *
FROM TRIANGLES
WHERE A = B AND B = C;

SELECT *
FROM TRIANGLES
WHERE A<>B AND B<>C AND A<>C;

SELECT * 
FROM TRIANGLES
WHERE A + B > C 
  AND A + C > B 
  AND B + C > A;

--
SELECT * 
FROM TRIANGLES
WHERE A*A + B*B = C*C 
   OR A*A + C*C = B*B 
   OR B*B + C*C = A*A;

SELECT A, B, C, (A + B + C) AS Perimeter
FROM TRIANGLES;

SELECT A, B, C, GREATEST(A, B, C) AS LargestSide
FROM TRIANGLES;

SELECT A, B, C, LEAST(A, B, C) AS SmallestSide
FROM TRIANGLES;
